# Creating a vector of numbers
numbers <- c(13, 21, 35, 42, 58)

# Exploring the data using built-in math functions
length(numbers)  # Finds how many items are in the vector
min(numbers)     # Finds the lowest value
max(numbers)     # Finds the highest value
mean(numbers)    # Calculates the average
median(numbers)  # Finds the middle value
sum(numbers)     # Adds all values together