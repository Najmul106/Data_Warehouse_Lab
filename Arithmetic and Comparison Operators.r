x <- 10
y <- 5

# --- Arithmetic Operations ---
x + y     # Addition
x - y     # Subtraction
x * y     # Multiplication
x / y     # Division
x ^ y     # Exponent
x %% y    # Modulus (Returns the remainder)
x %/% y   # Integer Division

# --- Relational (Comparison) Operations ---
x == y    # Equal to
x != y    # Not equal
x > y     # Greater than
x < y     # Less than
x >= y    # Greater than or equal to
x <= y    # Less than or equal to